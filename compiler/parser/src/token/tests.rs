//! Tests for token descriptions and the token type conversions.

use super::*;
use crate::FileId;
use dsl::core::SourceSpan;

#[test]
fn test_token_describe() {
    let token = Token {
        token_type: TokenType::Identifier,
        span: SourceSpan {
            start: 0,
            end: 5,
            file_id: FileId::new(),
        },
        line: 1,
        col: 2,
        text: "hello".to_string(),
    };
    let desc = token.describe();
    assert!(desc.contains("Identifier"));
    assert!(desc.contains("hello"));
    assert!(desc.contains("Ln 1,Col 2"));
}

#[test]
fn test_token_describe_with_newlines() {
    let token = Token {
        token_type: TokenType::Newline,
        span: SourceSpan {
            start: 0,
            end: 1,
            file_id: FileId::new(),
        },
        line: 3,
        col: 1,
        text: "\n".to_string(),
    };
    let desc = token.describe();
    assert!(desc.contains("\\n"));
}

