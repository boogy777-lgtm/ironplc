// generate-session-constants.js
//
// Reads each constant the VS Code client shares with the runtime from its
// resource file in compiler/runtime/resources/ - the same files the runtime
// crate compiles into its Rust constants with include! - and generates
// src/sessionConstants.ts, so the extension states the numbers nowhere else.
//
// The next shared constant is one more entry in CONSTANTS and one more
// resource file; this script is not copied.
//
// This script is plain JavaScript because it runs before TypeScript
// compilation - using TypeScript here would create a circular dependency.

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const RESOURCES = path.join(ROOT, '..', '..', 'compiler', 'runtime', 'resources');
const OUT_PATH = path.join(ROOT, 'src', 'sessionConstants.ts');

// One entry per shared constant: the resource file, the exported name, the
// Rust constant it mirrors, the inclusive range a value must lie in, and the
// doc comment of the export.
const CONSTANTS = [
  {
    file: 'session-port.txt',
    name: 'DEFAULT_SESSION_PORT',
    rust: 'DEFAULT_SESSION_PORT',
    min: 1,
    max: 65535,
    doc: 'The engineering port, TCP for the session',
  },
  {
    file: 'session-protocol.txt',
    name: 'SUPPORTED_SESSION_PROTOCOL',
    rust: 'SESSION_PROTOCOL_VERSION',
    min: 1,
    max: 4294967295,
    doc: 'The session protocol version this client speaks',
  },
];

function parseInteger(constant, text) {
  const trimmed = text.trim();
  if (!/^\d+$/.test(trimmed)) {
    throw new Error(`${constant.file} must contain one integer but contains "${trimmed}"`);
  }
  const value = Number(trimmed);
  if (value < constant.min || value > constant.max) {
    throw new Error(`${constant.file} value ${value} is outside ${constant.min}-${constant.max}`);
  }
  return value;
}

function main() {
  const values = CONSTANTS.map(c => parseInteger(c, fs.readFileSync(path.join(RESOURCES, c.file), 'utf-8')));
  const lines = [
    '// This file is automatically generated from the files in compiler/runtime/resources/.',
    '// Do not edit manually.',
    '',
  ];
  CONSTANTS.forEach((c, i) => {
    lines.push(`/** ${c.doc} (the Rust \`${c.rust}\`, from \`${c.file}\`). */`);
    lines.push(`export const ${c.name} = ${values[i]};`);
    lines.push('');
  });
  fs.writeFileSync(OUT_PATH, lines.join('\n'), 'utf-8');
  console.log(`Generated ${OUT_PATH} with ${CONSTANTS.map((c, i) => `${c.name}=${values[i]}`).join(', ')}.`);
}

main();
