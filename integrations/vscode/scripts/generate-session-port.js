// generate-session-port.js
//
// Reads the engineering port from compiler/runtime/resources/session-port.txt,
// the same file the runtime crate compiles into DEFAULT_SESSION_PORT, and
// generates src/sessionPort.ts so the extension states the number nowhere
// else.
//
// This script is plain JavaScript because it runs before TypeScript
// compilation — using TypeScript here would create a circular dependency.

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PORT_PATH = path.join(ROOT, '..', '..', 'compiler', 'runtime', 'resources', 'session-port.txt');
const OUT_PATH = path.join(ROOT, 'src', 'sessionPort.ts');

function parsePort(text) {
  const trimmed = text.trim();
  if (!/^\d+$/.test(trimmed)) {
    throw new Error(`session-port.txt must contain one integer but contains "${trimmed}"`);
  }
  const port = Number(trimmed);
  if (port < 1 || port > 65535) {
    throw new Error(`session-port.txt port ${port} is outside 1-65535`);
  }
  return port;
}

function main() {
  const port = parsePort(fs.readFileSync(PORT_PATH, 'utf-8'));
  const output = [
    '// This file is automatically generated from compiler/runtime/resources/session-port.txt.',
    '// Do not edit manually.',
    '',
    '/** The engineering port: TCP for the session (the Rust `DEFAULT_SESSION_PORT`). */',
    `export const DEFAULT_SESSION_PORT = ${port};`,
    '',
  ].join('\n');
  fs.writeFileSync(OUT_PATH, output, 'utf-8');
  console.log(`Generated ${OUT_PATH} with port ${port}.`);
}

main();
